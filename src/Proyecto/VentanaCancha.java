    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if(this.jTextField1.getText().equalsIgnoreCase("") ||
        this.jTextField2.getText().equalsIgnoreCase("") ||
        this.jTextField3.getText().equalsIgnoreCase("") ||
        this.jTextField4.getText().equalsIgnoreCase(""))
        {
            JOptionPane.showMessageDialog(null, "Complete todos los campos");
            return;
        }

        String codigo = this.jTextField1.getText();
        String nombre = this.jTextField2.getText();
        int capacidad = Integer.parseInt(this.jTextField3.getText());
        float tarifaBase = Float.parseFloat(this.jTextField4.getText());
        
        if(capacidad<=0)
        {
            JOptionPane.showMessageDialog(null, "La capacidad debe ser mayor a cero");
            return;
        }


        if(tarifaBase<=0)
        {
            JOptionPane.showMessageDialog(null, "La tarifa base debe ser mayor a cero");
            return;
        }


        String estado = "";

        if(this.jRadioButton4.isSelected())
        {
            estado = "Disponible";
        }
        else if(this.jRadioButton5.isSelected())
        {
            estado = "Ocupada";
        }
        else if(this.jRadioButton6.isSelected())
        {
            estado = "En Mantenimiento";
        }
        else
        {
            JOptionPane.showMessageDialog(null, "Seleccione un estado");
            return;
        }

        GC.Modificar(codigo,nombre,capacidad,tarifaBase,estado);

        CargarTabla();
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(this.jTextField1.getText().equalsIgnoreCase("") ||
        this.jTextField2.getText().equalsIgnoreCase("") ||
        this.jTextField3.getText().equalsIgnoreCase(""))
        {
            JOptionPane.showMessageDialog(null, "Complete todos los campos");
            return;
        }

        String codigo = this.jTextField1.getText();
        String nombre = this.jTextField2.getText();
        int capacidad = Integer.parseInt(this.jTextField3.getText());
        
        if(capacidad<=0)
        {
            JOptionPane.showMessageDialog(null, "La capacidad debe ser mayor a cero");
            return;
        }


        String estado = "";

        if(this.jRadioButton4.isSelected())
        {
            estado = "Disponible";
        }
        else if(this.jRadioButton5.isSelected())
        {
            estado = "Ocupada";
        }
        else if(this.jRadioButton6.isSelected())
        {
            estado = "En Mantenimiento";
        }
        else
        {
            JOptionPane.showMessageDialog(null, "Seleccione un estado");
            return;
        }

        if(this.jRadioButton1.isSelected())
        {
            Cancha5 ref = new Cancha5(codigo,nombre,"Futbol 5",capacidad,estado);
            GC.Ingresar(ref);
        }
        else if(this.jRadioButton2.isSelected())
        {
            Cancha7 ref = new Cancha7(codigo,nombre,"Futbol 7",capacidad,estado);
            GC.Ingresar(ref);
        }
        else if(this.jRadioButton3.isSelected())
        {
            Cancha11 ref = new Cancha11(codigo,nombre,"Futbol 11",capacidad,estado);
            GC.Ingresar(ref);
        }
        else
        {
            JOptionPane.showMessageDialog(null, "Seleccione un tipo de cancha");
            return;
        }

        CargarTabla();
    }//GEN-LAST:event_jButton1ActionPerformed

